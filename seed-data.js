window.SEED_TIME_WINDOWS = [
  "08:00 AM - 10:00 AM",
  "10:00 AM - 12:00 PM",
  "12:00 PM - 02:00 PM",
  "02:00 PM - 04:00 PM",
  "04:00 PM - 06:00 PM",
  "06:00 PM - 08:00 PM"
];

function generateDefaultSlots(storeId, date) {
  return window.SEED_TIME_WINDOWS.map(tw => {
    let booked = 1;
    if (date === "Today" && tw.includes("08:00 AM")) {
      booked = 5; // FULL
    } else if (date === "Today" && tw.includes("10:00 AM")) {
      booked = 4; // 1 left
    } else if (date === "Tomorrow" && tw.includes("08:00 AM - 10:00 AM")) {
      booked = 2; // 3 left
    } else if (date === "Tomorrow" && tw.includes("06:00 PM")) {
      booked = 3; // 2 left
    }

    return {
      id: `${storeId}_${date.toLowerCase()}_${tw.replace(/ /g, '_').replace(/:/g, '')}`,
      store_id: storeId,
      date: date,
      time_window: tw,
      max_capacity: 5,
      booked_count: booked,
      is_full: booked >= 5,
      remaining_capacity: Math.max(0, 5 - booked)
    };
  });
}

window.generateDefaultSlots = generateDefaultSlots;
